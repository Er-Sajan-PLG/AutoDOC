def generate(check=False, only=None, findings=None):
    failures = []
    entries = load_map()['generated']
    if only and only not in {entry['id'] for entry in entries}:
        raise ValueError('Unknown generator ID: ' + only)
    for entry in entries:
        if only and entry['id'] != only:
            continue
        target = safe_path(entry['target'])
        expected = GENERATORS[entry['generator']](entry)
        if target.suffix == '.md':
            expected = expected.rstrip('\n') + '\n'
        if target.exists() and target.read_text(encoding='utf-8') == expected:
            continue
        if check:
            failures.append(f"{entry['target']} (sources: {', '.join(entry['sources'])}); run make docs:generate")
            if findings is not None:
                findings.append({'rule': 'drift', 'location': entry['target'],
                                 'detail': f"generated from {', '.join(entry['sources'])}",
                                 'fix': 'run make docs:generate'})
        else:
            if target.suffix == '.md' and target.exists() and not target.read_text(encoding='utf-8').startswith(
                    '<!-- AUTO-GENERATED BY AUTODOC ENGINE.'):
                raise ValueError('Refusing to overwrite unmarked Markdown target: ' + entry['target'])
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding='utf-8')
            print('Updated', entry['target'])
    if failures:
        print('Generated documentation drift:\n' + '\n'.join(failures), file=sys.stderr)
    return not failures


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT, text=True).strip()


def changed(base=None, staged=False):
    if base:
        result = git('diff', '--name-only', '--diff-filter=ACMRT', base + '...HEAD')
    else:
        result = git('diff', '--cached' if staged else 'HEAD', '--name-only', '--diff-filter=ACMRT')
    return set(result.splitlines()) if result else set()


def matches(file, pattern):
    return fnmatch.fnmatchcase(file, pattern) or (pattern.endswith('/**') and file.startswith(pattern[:-3]))


def impact(base=None, staged=False):
    files = changed(base, staged)
    data = load_map()
    failures = []
    for rule in data['review']:
        sources = [f for f in files if any(matches(f, p) for p in rule['sources'])]
        if sources and not any(t in files for t in rule['targets']):
            message = f"{rule['id']}: changed {', '.join(sorted(sources))}; review {', '.join(rule['targets'])}"
            if rule['level'] == 'block':
                failures.append(message)
            else:
                print('WARNING:', message)
    changelog = data.get('changelog')
    if changelog and any(any(matches(f, p) for p in changelog['sources']) for f in files):
        if changelog['target'] not in files:
            failures.append('User-facing change requires ' + changelog['target'])
    living = data['living']
    if any(any(matches(f, p) for p in living['sources']) for f in files):
        missing = [t for t in living['targets'] if t not in files]
        if missing:
            failures.append('Living state not updated: ' + ', '.join(missing))
    if failures:
        print('\n'.join(failures), file=sys.stderr)
    return not failures


def parse_frontmatter(path):
    return parse_frontmatter_text(path.read_text(encoding='utf-8'))


def parse_frontmatter_text(text):
    if text.startswith('<!-- AUTO-GENERATED BY AUTODOC ENGINE. '):
        text = text.split('\n', 1)[1]
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        raise ValueError('missing YAML frontmatter')
    section = text.split('\n---\n', 1)[0][4:]
    # Constrained YAML subset: one scalar or inline list per key; no nested mappings.
    fields = {}
    for line in section.splitlines():
        if not re.match(r'^[a-z_]+: ', line):
            raise ValueError('invalid metadata line: ' + line)
        key, value = line.split(': ', 1)
        if key in fields:
            raise ValueError('duplicate metadata key: ' + key)
        fields[key] = value.strip().strip('"')
    return fields


def controlled():
    paths_ = list((ROOT / 'docs').rglob('*.md')) + list((ROOT / 'CONTROL').rglob('*.md'))
    paths_ += list((ROOT / 'EXAMPLE-PROJECT/docs').rglob('*.md'))
    paths_ += list((ROOT / 'examples/ai-agent-example/docs').rglob('*.md'))
    paths_ += list((ROOT / 'examples/local-tools-example/docs').rglob('*.md'))
    paths_ += [ROOT / name for name in ('CURRENT-STATE.md', 'NEXT-ACTION.md', 'RECENT-CHANGES.md',
                                       'AGENTS.md', 'CLAUDE.md', 'AGENT-MEMORY.md',
                                       'ANTI-PATTERNS-FOR-AGENT.md', 'CONTEXT-SNAPSHOT.md',
                                       'TASK-FOR-AGENT.md')]
    return sorted(set(paths_))



def validate_staged():
    """Read Git index blobs, not potentially different worktree copies, for staged metadata."""
    changed_files = git('diff', '--cached', '--name-only', '--diff-filter=ACMRT').splitlines()
    controlled_roots = {'CURRENT-STATE.md', 'NEXT-ACTION.md', 'RECENT-CHANGES.md',
                        'AGENTS.md', 'CLAUDE.md', 'AGENT-MEMORY.md',
                        'ANTI-PATTERNS-FOR-AGENT.md', 'CONTEXT-SNAPSHOT.md', 'TASK-FOR-AGENT.md'}
    controlled_dirs = ('docs/', 'CONTROL/', 'EXAMPLE-PROJECT/docs/',
                       'examples/ai-agent-example/docs/', 'examples/local-tools-example/docs/')
    schema = json.loads((ROOT / 'CONTROL/metadata/FRONT-MATTER-SCHEMA.json').read_text())
    errors = []
    for name in changed_files:
        if not name.endswith('.md') or not (name in controlled_roots or name.startswith(controlled_dirs)):
            continue
        try:
            text = subprocess.check_output(['git', 'show', ':' + name], cwd=ROOT, text=True)
            meta = parse_frontmatter_text(text)
            missing = [key for key in schema['required'] if not meta.get(key)]
            if missing:
                raise ValueError('missing staged metadata: ' + ', '.join(missing))
            if set(meta) - set(schema['properties']):
                raise ValueError('unknown staged metadata keys')
            for key, spec in schema['properties'].items():
                if 'enum' in spec and meta[key] not in spec['enum']:
                    raise ValueError('invalid staged ' + key + ': ' + meta[key])
            for key in ('last_verified', 'last_reviewed', 'last_updated', 'effective_date', 'next_review'):
                date.fromisoformat(meta[key])
            if meta['auto_generated'] not in ('true', 'false') or (
                    meta['auto_generated'] == 'true') != text.startswith(
                    '<!-- AUTO-GENERATED BY AUTODOC ENGINE. '):
                raise ValueError('staged generated marker and auto_generated disagree')
        except (ValueError, KeyError, subprocess.CalledProcessError) as exc:
            errors.append(name + ': ' + str(exc))
    for error in errors:
        print(error, file=sys.stderr)
    return not errors

def validate(freshness=False, now=None, findings=None):
    schema_path = ROOT / 'CONTROL/metadata/FRONT-MATTER-SCHEMA.json'
    if not schema_path.is_file():
        # A repository that has not adopted AutoDOC's metadata has no review dates to read, so
        # there is nothing here to validate. enforce.py reports that freshness could not run
        # rather than letting the absence look like a clean result.
        return True
    schema = json.loads(schema_path.read_text())
    required = schema['required']
    seen, errors, relationships, supersedes = set(), [], [], {}
    today = now or date.today()
    for path in controlled():
        relative = str(path.relative_to(ROOT))
        try:
            fields = parse_frontmatter(path)
            missing = [key for key in required if not fields.get(key)]
            if missing:
                raise ValueError('missing: ' + ', '.join(missing))
            if fields['id'] in seen:
                raise ValueError('duplicate id: ' + fields['id'])
            seen.add(fields['id'])
            extra = set(fields) - set(schema['properties'])
            if extra:
                raise ValueError('unknown metadata keys: ' + ', '.join(sorted(extra)))
            for key, spec in schema['properties'].items():
                if 'enum' in spec and fields[key] not in spec['enum']:
                    raise ValueError('invalid ' + key + ': ' + fields[key])
            for key in ('last_verified', 'last_reviewed', 'last_updated', 'effective_date', 'next_review'):
                date.fromisoformat(fields[key])
            if date.fromisoformat(fields['next_review']) < date.fromisoformat(fields['last_verified']):
                raise ValueError('next_review before last_verified')
            if not fields['owner'].startswith('@') or not fields['reviewer'].startswith('@'):
                raise ValueError('owner and reviewer must identify a person or team')
            try:
                related = json.loads(fields['related'])
            except json.JSONDecodeError as exc:
                raise ValueError('related must be a JSON-compatible YAML list') from exc
            if not isinstance(related, list) or not all(isinstance(id_, str) for id_ in related):
                raise ValueError('related must be a list of document IDs')
            relationships.append((relative, related + ([] if fields['supersedes'] == 'null' else [fields['supersedes']])))
            if fields['supersedes'] != 'null':
                supersedes[fields['id']] = fields['supersedes']
            if fields['auto_generated'] == 'true' and fields['source_of_truth'] == 'human':
                raise ValueError('generated document needs a source of truth')
            days = int(fields['review_days'])
            if days < 1:
                raise ValueError('review_days must be positive')
            due = min(date.fromisoformat(fields['next_review']),
                      date.fromisoformat(fields['last_verified']) + timedelta(days=days))
            if freshness and fields['auto_generated'] != 'true' and today > due:
                msg = 'overdue review (critical)' if fields['criticality'] == 'critical' else 'overdue review (warning)'
                if findings is not None:
                    critical = fields['criticality'] == 'critical'
                    findings.append({'rule': 'freshness.critical' if critical else 'freshness.review',
                                     'location': relative, 'detail': msg,
                                     'fix': 'review the document, or change review_days with a reason'})
                if fields['criticality'] == 'critical':
                    errors.append(relative + ': ' + msg)
                else:
                    print('WARNING:', relative + ': ' + msg)
            if fields['auto_generated'] not in ('true', 'false'):
                raise ValueError('auto_generated must be true or false')
            marked = path.read_text(encoding='utf-8').startswith('<!-- AUTO-GENERATED BY AUTODOC ENGINE. ')
            if (fields['auto_generated'] == 'true') != marked:
                raise ValueError('generated marker and auto_generated disagree')
        except (ValueError, KeyError) as error:
            errors.append(relative + ': ' + str(error))
    for path, ids in relationships:
        for id_ in ids:
            if id_ not in seen:
                errors.append(path + ': unknown related/superseded document ID ' + id_)
    try:
        check_supersedes_cycles(supersedes)
    except ValueError as exc:
        errors.append(str(exc))
    for error in errors:
        print(error, file=sys.stderr)
    return not errors




def replace_block(text, body):
    start, end = '<!-- auto:start -->', '<!-- auto:end -->'
    if (start in text) != (end in text):
        raise ValueError('Incomplete state block; repair both auto markers')
    if start not in text:
        return text.rstrip() + '\n\n' + start + '\n' + body + '\n' + end + '\n'
    return text.split(start)[0] + start + '\n' + body + '\n' + end + text.split(end, 1)[1]


def update_state(base=None, staged=False):
    """Update observable blocks only; preserve manually reviewed context and next action."""
    files = sorted(changed(base, staged) - {'CURRENT-STATE.md', 'NEXT-ACTION.md', 'RECENT-CHANGES.md'})
    if staged and not files:
        return
    log = git('log', '-20', '--format=%h %ad %s', '--date=short').splitlines()
    docs = [parse_frontmatter(p) for p in controlled()]
    generated = sum(d['auto_generated'] == 'true' for d in docs)
    overdue = sum(d['auto_generated'] == 'false' and
                  date.today() > min(date.fromisoformat(d['next_review']),
                                     date.fromisoformat(d['last_verified']) + timedelta(days=int(d['review_days'])))
                  for d in docs)
    cat_count = sum(len(domain['documents']) for catalog in ('CATALOG-A', 'CATALOG-B')
                    for domain in json.loads((ROOT / catalog / 'INDEX.yaml').read_text())['domains'])
    stats = (f'- Catalog types: {cat_count} (not necessarily instantiated).\n'
             f'- Controlled docs: {len(docs)} ({generated} generated, {len(docs)-generated} human-owned).\n'
             f'- Overdue human-owned docs: {overdue}.\n'
             '- Open gaps: see `docs/00-governance/ENGINE-COVERAGE.md`; this block does not infer intent.')
    paths = '\n'.join('- `' + name + '`' for name in files[:20]) or '- None staged or changed.'
    if len(files) > 20:
        paths += f'\n- … and {len(files) - 20} more; use git diff --cached --name-only.'
    recent = ('## Last 20 Git commits\n\n' + ('\n'.join('- ' + line for line in log) or '- No commits.') +
              '\n\n## Changed paths at update time\n\n' + paths)
    for name, body in (('CURRENT-STATE.md', stats), ('RECENT-CHANGES.md', recent)):
        path = ROOT / name
        text = path.read_text(encoding='utf-8')
        result = replace_block(text, body)
        if text != result:
            path.write_text(result, encoding='utf-8')
            print('Updated', name, '(review and stage explicitly)')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate', 'drift', 'impact', 'validate', 'freshness', 'state'])
    parser.add_argument('--base', help='Git merge base/ref for PR comparisons')
    parser.add_argument('--staged', action='store_true')
    parser.add_argument('--only', help='Only one mapped generated entry ID')
    parser.add_argument('--check', action='store_true', help='Check instead of writing (generate only)')
    parser.add_argument('--write', action='store_true', help='Explicit write mode (generate only)')
    args = parser.parse_args()
    try:
        if args.command == 'generate':
            if args.check and args.write:
                parser.error('--check and --write are mutually exclusive')
            ok = generate(check=args.check, only=args.only)
        elif args.command == 'drift':
            ok = generate(check=True)
        elif args.command == 'impact':
            ok = impact(args.base, args.staged)
        elif args.command == 'state':
            update_state(args.base, args.staged)
            ok = True
        else:
            ok = validate(freshness=args.command == 'freshness')
        sys.exit(0 if ok else 1)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print('AutoDOC error:', error, file=sys.stderr)
        sys.exit(2)


if __name__ == '__main__':
    main()
