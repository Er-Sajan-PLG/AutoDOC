def catalog(entry):
    """Index catalog domains and stable IDs, without implying adoption of every type."""
    lines = [header('DOC-CAT-001', 'AutoDOC catalog reference', 'CATALOG-*/INDEX.yaml'),
             '# AutoDOC catalog reference', '',
             'Generated from the three catalog indices. These are possible documents, not completed work.', '']
    for path in paths(entry):
        data = json.loads(path.read_text(encoding='utf-8'))
        lines.extend([f'## {path.parent.name}', ''])
        if 'domains' in data:
            lines.extend(['| Domain | Purpose | Types | IDs |', '| --- | --- | ---: | --- |'])
            for domain in data['domains']:
                docs = domain['documents']
                ids = ', '.join(f'`{doc["id"]}`' for doc in docs)
                lines.append(f"| {domain['domain']} | {domain['purpose']} | {len(docs)} | {ids} |")
            lines.extend(['', f"**Total types:** {sum(len(d['documents']) for d in data['domains'])}.", ''])
        else:
            lines.extend(['| Control ID | Artifact | Purpose |', '| --- | --- | --- |'])
            for artifact in data['artifacts']:
                lines.append(f"| `{artifact['id']}` | `{artifact['path']}` | {artifact['purpose']} |")
            lines.append('')
    return '\n'.join(lines) + '\n'


def workflows(entry):
    """List workflow declarations with a hash, so any CI edit requires review."""
    lines = [header('DOC-CI-001', 'AutoDOC workflow reference', '.github/workflows/*.yml'),
             '# AutoDOC workflow reference', '',
             'Derived from workflow files. A listing or green check does not establish branch protection.', '',
             '| Workflow | Name | Jobs | Declared purpose | SHA-256 |', '| --- | --- | --- | --- | --- |']
    for path in paths(entry):
        text = path.read_text(encoding='utf-8')
        first = text.splitlines()[0].strip() if text else ''
        name = re.search(r'^name:\s*(.+)$', text, re.M)
        if not first.startswith('# ') or not name:
            raise ValueError(f'Workflow needs an initial purpose comment and name: {path}')
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        jobs_section = text.split('\njobs:\n', 1)
        if len(jobs_section) != 2:
            raise ValueError(f'Workflow missing jobs block: {path}')
        job_names = re.findall(r'^  ([A-Za-z][A-Za-z0-9_-]*):\s*$', jobs_section[1], re.M)
        if not job_names:
            raise ValueError(f'Workflow declares no jobs: {path}')
        lines.append(f'| `{path.relative_to(ROOT)}` | {name.group(1)} | {", ".join(job_names)} | {first[2:]} | `{digest}` |')
    return '\n'.join(lines) + '\n'


def outline(entry):
    lines = [header('DOC-OUT-001', 'Documentation outline', ', '.join(entry['sources'])),
             '# Documentation outline', '', 'ATX headings from configured human-owned Markdown sources.', '']
    for path in paths(entry):
        if path.read_text(encoding='utf-8').startswith('<!-- AUTO-GENERATED BY AUTODOC ENGINE.'):
            continue  # Generated targets are derived, not authoritative heading sources.
        lines.extend([f'## `{path.relative_to(ROOT)}`', ''])
        entries = headings(path)
        if path.is_relative_to(ROOT / 'TEMPLATES'):
            entries = [row for row in entries if row[1] == 1]
        for number, level, title in entries:
            lines.append(f'- L{level} line {number}: {title}')
        lines.append('')
    return '\n'.join(lines) + '\n'


def code_inventory(entry):
    lines = [header('DOC-CODE-001', 'Python code inventory', ', '.join(entry['sources'])),
             '# Python code inventory', '', 'AST-extracted Python declarations; no call graph or behavior claims.', '',
             '| Source | Line | Kind | Symbol | Signature |', '| --- | ---: | --- | --- | --- |']
    for path in paths(entry):
        module = str(path.relative_to(ROOT).with_suffix('')).replace('/', '.')
        kind_module = 'package' if path.name == '__init__.py' else 'module'
        lines.append(f'| `{path.relative_to(ROOT)}` | 1 | {kind_module} | `{module}` | — |')
        for line, kind, name, signature in python_symbols(path):
            lines.append(f'| `{path.relative_to(ROOT)}` | {line} | {kind} | `{name}` | `{signature}` |')
    return '\n'.join(lines) + '\n'


