def safe_path(value):
    path = Path(value)
    if path.is_absolute() or '..' in path.parts or not (ROOT / path).resolve().is_relative_to(ROOT):
        raise ValueError('Target must be inside the repository: ' + value)
    return ROOT / path


def load_map():
    if not MAP.is_file():
        # No declared generators, so drift has nothing to compare here. A repository that has not
        # adopted generated documents has no drift, which is different from a broken generator.
        return {'version': 1, 'generated': []}
    data = json.loads(MAP.read_text(encoding='utf-8'))
    if data.get('version') != 1:
        raise ValueError('Unsupported sync map version')
    ids, targets = set(), set()
    for entry in data['generated']:
        if entry['id'] in ids or entry['target'] in targets:
            raise ValueError('Duplicate generator id/target')
        ids.add(entry['id'])
        targets.add(entry['target'])
        safe_path(entry['target'])
        if entry['generator'] not in GENERATORS:
            raise ValueError('Unknown generator: ' + entry['generator'])
        for source in entry['sources']:
            if Path(source).is_absolute() or '..' in Path(source).parts:
                raise ValueError('Source must be inside the repository: ' + source)
            matches_ = [p for p in ROOT.glob(source) if p.is_file()]
            if not matches_:
                raise ValueError('Missing source files: ' + source + '; fix docs/.doc-sync-map.yaml')
            if any(not p.resolve().is_relative_to(ROOT.resolve()) for p in matches_):
                raise ValueError('Source escapes repository: ' + source)
    return data


def paths(entry):
    return sorted({p for pattern in entry['sources'] for p in ROOT.glob(pattern) if p.is_file()})


def header(doc_id, title, source):
    # Generated content is deterministic: no timestamp of the build or machine paths.
    return (f'<!-- AUTO-GENERATED BY AUTODOC ENGINE. DO NOT EDIT MANUALLY. SOURCE: {source} -->\n'
            f'---\nid: {doc_id}\ntitle: {title}\ntype: REF\nowner: "@Er-Sajan-PLG"\n'
            'reviewer: "@Er-Sajan-PLG"\nclassification: public\nstatus: approved\nversion: "1.0"\n'
            'effective_date: 2026-09-26\nnext_review: 2099-01-01\nsource_of_truth: '
            f'{source}\nsupersedes: null\nrelated: []\ncriticality: low\nreview_days: 365\n'
            'last_verified: 2026-09-26\nlast_reviewed: 2026-09-26\nlast_updated: 2026-09-26\n'
            'auto_generated: true\n---\n\n')


