def relationship_graph(entry):
    edges = []
    for path in controlled():
        fields = parse_frontmatter(path)
        related = json.loads(fields['related'])
        for target in related:
            edges.append({'from': fields['id'], 'to': target, 'kind': 'related'})
        if fields['supersedes'] != 'null':
            edges.append({'from': fields['id'], 'to': fields['supersedes'], 'kind': 'supersedes'})
    return json.dumps({'version': 1, 'source': 'frontmatter related/supersedes',
                       'note': 'AUTO-GENERATED; semantics require human review.',
                       'edges': sorted(edges, key=lambda e: (e['from'], e['kind'], e['to']))}, indent=2) + '\n'

