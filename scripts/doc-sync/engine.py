def check_supersedes_cycles(links):
    """A supersession chain must terminate (related links may intentionally be cyclic)."""
    for source in links:
        visited = set()
        current = source
        while current in links:
            if current in visited:
                raise ValueError('Circular supersedes chain starting at ' + source)
            visited.add(current)
            current = links[current]


def relationship_visualization(entry):
    """Mermaid of real frontmatter and mapped source relationships only."""
    links = []
    for path in controlled():
        meta = parse_frontmatter(path)
        for related in json.loads(meta['related']):
            links.append((meta['id'], related, 'related'))
        if meta['supersedes'] != 'null':
            links.append((meta['id'], meta['supersedes'], 'supersedes'))
    check_supersedes_cycles({a: b for a, b, kind in links if kind == 'supersedes'})
    for mapping in load_map()['generated']:
        for source in mapping['sources']:
            links.append((source, mapping['target'], 'generates'))
    for catalog_name in ('CATALOG-A', 'CATALOG-B'):
        catalog_data = json.loads((ROOT / catalog_name / 'INDEX.yaml').read_text())
        for domain in catalog_data['domains']:
            for doc in domain['documents']:
                links.extend((doc['id'], doc['template'] + suffix, 'template') for suffix in ('', '.blank', '.example'))
    import hashlib
    nodes = sorted({node for a, b, _ in links for node in (a, b)})
    ids = {node: 'n' + hashlib.sha256(node.encode()).hexdigest()[:16] for node in nodes}
    lines = [header('DOC-REL-001', 'Mapped document relationships', 'docs/.doc-sync-map.yaml'),
             '# Mapped document relationships', '',
             'Directed links are derived from frontmatter, mapped generators and catalog templates. '
             'Absence of an edge is not evidence of independence. All controlled docs are indexed by the master index.', '',
             '```mermaid', 'flowchart LR']
    for node in nodes:
        safe = node.replace('"', "'").replace('|', '/')
        lines.append(f'    {ids[node]}["{safe}"]')
    for a, b, kind in sorted(set(links)):
        lines.append(f'    {ids[a]} -->|{kind}| {ids[b]}')
    lines += ['```', '']
    return '\n'.join(lines) + '\n'

